// WHAT:   the full filter panel — source/type/price/ZIP controls, the
//   motivation checkboxes and the DOM range slider, plus the shown/of count,
//   ShareLink and FilterNotices.
// WHY:    the single place a view is composed; its accessibility fixes (S5/S6)
//   and the two disabled "Zillow/USA/New York" selects are explained inline.
// INPUTS: `value` (FilterState from lib/useFilters), onChange/onReset
//   callbacks, and the shown/total row counts from the caller's fetch.
// OUTPUTS: the <aside> panel; every change goes through onChange (the caller
//   writes the URL).
// CALLERS: components/explorer/{Full,Compact}Explorer.tsx (so /map, /data and
//   / share one panel).
"use client";
import { useId } from "react";
import FilterNotices from "./FilterNotices";
import ShareLink from "./ShareLink";
import type { MotivationScore } from "@/lib/api-types";
import type { FilterState } from "@/lib/filters";
import { SCORES } from "@/lib/scores";

const TYPES = ["house", "condo", "co-op", "townhouse", "multi-family", "land", "other"];

export default function Filters({
  value,
  onChange,
  onReset,
  shown,
  total,
}: {
  value: FilterState;
  onChange: (patch: Partial<FilterState>) => void;
  onReset: () => void;
  shown: number | null;
  total: number | null;
}) {
  // ---- identity helpers: unique ids for every labelled control ----
  // S5 — every control needs a programmatic name. The panel used to render
  // bare `<label>` siblings, so the Type select and the DOM slider (the two
  // enabled controls) had NO accessible name at all, and `label:not([for])`
  // matched nine elements. Each label now has an explicit `htmlFor` pointing
  // at its control's id, generated by useId so the ids stay unique if the
  // panel is ever rendered twice in one document.
  // Verified by: NOTHING (gap) — no key re-runs axe's `label:not([for])`
  //   rule (data_keyboard.tabStops: 9 counts keyboard stops, not labels).
  const uid = useId();
  const id = (k: string) => `${uid}-${k}`;

  const toggleScore = (s: MotivationScore) => {
    const has = value.score.includes(s);
    onChange({ score: has ? value.score.filter((x) => x !== s) : [...value.score, s] });
  };
  // ---- render: counts + ShareLink + notices, then the control stack ----
  return (
    <aside className="panel space-y-3 p-3 text-sm text-zinc-200">
      <div className="flex items-center justify-between">
        <span className="font-semibold">Filters</span>
        <button className="tap text-xs underline" onClick={onReset}>Reset</button>
      </div>
      <div className="flex flex-wrap items-center justify-between gap-2 text-xs text-zinc-400">
        <span>{total != null ? `${shown ?? "…"} of ${total} shown` : `${shown ?? "…"} shown`}</span>
        {/* The filter panel is where a view is composed, so it is where the
            shareable link belongs (roadmap 1.3).
            Verified by: NOTHING (gap) — no key checks ShareLink's placement. */}
        <ShareLink />
      </div>
      {/* S8 — say so when the link carried a param we could not honour.
          Verified by: NOTHING (gap) — no key loads /map with an
          un-honourable param to compare the notice. */}
      <FilterNotices value={value} />
      <div>
        <label htmlFor={id("source")} className="font-medium text-zinc-100">Source</label>
        <select
          id={id("source")}
          disabled
          className="mt-1 w-full rounded border border-zinc-700 bg-zinc-800 p-1"
          value="zillow"
        >
          <option value="zillow">Zillow</option>
        </select>
      </div>
      <div className="grid grid-cols-2 gap-2">
        <div>
          <label htmlFor={id("country")} className="font-medium text-zinc-100">Country</label>
          <select
            id={id("country")}
            disabled
            className="mt-1 w-full rounded border border-zinc-700 bg-zinc-800 p-1"
            value="USA"
          >
            <option>USA</option>
          </select>
        </div>
        <div>
          <label htmlFor={id("city")} className="font-medium text-zinc-100">City</label>
          <select
            id={id("city")}
            disabled
            className="mt-1 w-full rounded border border-zinc-700 bg-zinc-800 p-1"
            value="New York"
          >
            <option>New York</option>
          </select>
        </div>
      </div>
      <div>
        <span className="font-medium text-zinc-100">Motivation</span>
        <div className="mt-1 flex gap-3">
          {SCORES.map((s) => (
            <label key={s} htmlFor={id(`score-${s}`)} className="tap gap-1.5">
              {/* S6 — 13x13 was the worst tap target in the report on the
                  product's central control; 24x24 (size-6) is the minimum.
                  Verified by: shots/phase3-runtime-gate.json →
                  data_keyboard.checkboxFlipped + lastStop.cls "size-6 shrink-0". */}
              <input
                id={id(`score-${s}`)}
                className="size-6 shrink-0"
                type="checkbox"
                checked={value.score.includes(s)}
                onChange={() => toggleScore(s)}
              />
              {s}
            </label>
          ))}
        </div>
        {/* The "no score selected" / "score=Bogus" explanation lives in
            FilterNotices above, so it reads the same here and on /. */}
      </div>
      <div>
        <label htmlFor={id("dom")} className="font-medium text-zinc-100">DOM ≥ {value.minDom} days</label>
        {/* S6 — the range input's own box was 16px tall.
            Verified by: shots/phase3-runtime-gate.json →
            data_keyboard.rangeOperable (rangeFrom 60 → rangeTo 65); the 16px
            figure is QA-sweep evidence, not a gate key. */}
        <input
          id={id("dom")}
          className="mt-0.5 h-6 w-full"
          type="range" min={0} max={180} step={5} value={value.minDom}
          onChange={(e) => onChange({ minDom: Number(e.target.value) })}
        />
      </div>
      <div className="grid grid-cols-2 gap-2">
        <div>
          <label htmlFor={id("min-price")} className="font-medium text-zinc-100">Min price</label>
          <input
            id={id("min-price")}
            type="number" placeholder="No min" className="mt-1 w-full rounded border border-zinc-700 bg-zinc-950 p-1"
            value={value.minPrice ?? ""} onChange={(e) => onChange({ minPrice: e.target.value ? Number(e.target.value) : null })}
          />
        </div>
        <div>
          <label htmlFor={id("max-price")} className="font-medium text-zinc-100">Max price</label>
          <input
            id={id("max-price")}
            type="number" placeholder="No max" className="mt-1 w-full rounded border border-zinc-700 bg-zinc-950 p-1"
            value={value.maxPrice ?? ""} onChange={(e) => onChange({ minPrice: value.minPrice, maxPrice: e.target.value ? Number(e.target.value) : null })}
          />
        </div>
      </div>
      <div>
        <label htmlFor={id("type")} className="font-medium text-zinc-100">Type</label>
        <select
          id={id("type")}
          className="mt-1 w-full rounded border border-zinc-700 bg-zinc-950 p-1"
          value={value.type ?? ""}
          onChange={(e) => onChange({ type: e.target.value || null })}
        >
          <option value="">Any</option>
          {TYPES.map((t) => <option key={t} value={t}>{t}</option>)}
        </select>
      </div>
      <div>
        <label htmlFor={id("zips")} className="font-medium text-zinc-100">ZIPs (comma-separated)</label>
        <input
          id={id("zips")}
          type="text" placeholder="All ZIPs" className="mt-1 w-full rounded border border-zinc-700 bg-zinc-950 p-1"
          value={value.zips.join(", ")}
          onChange={(e) => onChange({ zips: e.target.value.split(",").map((s) => s.trim()).filter(Boolean) })}
        />
      </div>
    </aside>
  );
}
